import { randomBytes } from 'node:crypto';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import type { LocationPreferenceId, NoticeLevel } from '@hearth/api-types';
import type { StoredPreferences } from '@hearth/shared/eshtek/preferences';

/** What Hearth remembers about an app it installed (TrueNAS remains the source of truth for the app itself). */
export interface InstalledAppRecord {
  catalogApp: string;
  train: string;
  /** Curation (install script) version, null when installed with TrueNAS defaults. */
  scriptVersion: string | null;
  locations: LocationPreferenceId[];
  /** Datasets created for the app; deleted on uninstall only when the user asks to remove data. */
  directories: { dataset: string; path: string; snapshotId?: string }[];
  installedAt: string;
}

/** A notification generated by Hearth itself (TrueNAS alerts are read live). */
export interface HearthNotice {
  id: string;
  level: NoticeLevel;
  title: string;
  message: string;
  time: string;
  dismissed: boolean;
  link: string | null;
}

export interface HearthState {
  version: 1;
  /** Secret used to sign session cookies. */
  sessionSecret: string;
  admin?: {
    username: string;
    passwordHash: string;
  };
  truenas?: {
    url: string;
    apiKey: string;
  };
  server: {
    name?: string;
    setupCompletedAt?: string;
  };
  preferences: StoredPreferences;
  /** ZFS pool name → display name chosen by the user. */
  poolNames: Record<string, string>;
  apps: Record<string, InstalledAppRecord>;
  notices: HearthNotice[];
}

function defaultState(): HearthState {
  return {
    version: 1,
    sessionSecret: randomBytes(32).toString('base64url'),
    server: {},
    preferences: { locations: {} },
    poolNames: {},
    apps: {},
    notices: [],
  };
}

/** Small JSON-file store. Writes are serialized and atomic (write + rename). */
export class StateStore {
  private state: HearthState = defaultState();
  private writing: Promise<void> = Promise.resolve();
  readonly file: string;

  constructor(dataDir: string) {
    this.file = join(dataDir, 'state.json');
  }

  async load(): Promise<void> {
    try {
      const raw = JSON.parse(await readFile(this.file, 'utf8')) as Partial<HearthState>;
      this.state = {
        ...defaultState(),
        ...raw,
        server: { ...raw.server },
        preferences: { locations: {}, ...raw.preferences },
        poolNames: { ...raw.poolNames },
        apps: { ...raw.apps },
        notices: raw.notices ?? [],
      };
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
      await this.persist();
    }
  }

  get(): Readonly<HearthState> {
    return this.state;
  }

  async update(mutate: (state: HearthState) => void): Promise<void> {
    const next = structuredClone(this.state);
    mutate(next);
    this.state = next;
    await this.persist();
  }

  private persist(): Promise<void> {
    const snapshot = JSON.stringify(this.state, null, 2);
    this.writing = this.writing.then(async () => {
      await mkdir(dirname(this.file), { recursive: true, mode: 0o700 });
      const tmp = `${this.file}.tmp`;
      await writeFile(tmp, snapshot, { mode: 0o600 });
      await rename(tmp, this.file);
    });
    return this.writing;
  }
}
