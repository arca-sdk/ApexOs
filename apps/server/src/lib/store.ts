import { randomBytes } from 'node:crypto';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import type { BackupOptions, DriveDiagnosis, DriveErrorCounts, DriveHealthEvent, LocationPreferenceId, NoticeLevel, SmartSummary } from '@apexos/api-types';
import type { StoredPreferences } from '@apexos/shared/eshtek/preferences';
import type { StoredEncryption } from '../services/encryption.ts';

/** What ApexOs remembers about an app it installed (TrueNAS remains the source of truth for the app itself). */
export interface InstalledAppRecord {
  catalogApp: string;
  train: string;
  /** Curation (install script) version, null when installed with TrueNAS defaults. */
  scriptVersion: string | null;
  locations: LocationPreferenceId[];
  /** Datasets created for the app; deleted on uninstall only when the user asks to remove data. */
  directories: { dataset: string; path: string; snapshotId?: string }[];
  installedAt: string;
}

/** A notification generated by ApexOs itself (TrueNAS alerts are read live). */
export interface ApexOsNotice {
  id: string;
  level: NoticeLevel;
  title: string;
  message: string;
  time: string;
  dismissed: boolean;
  link: string | null;
}

/** What ApexOs remembers about one drive's errors (see services/drive-health.ts). Keyed by disk identifier. */
export interface DriveHealthRecord {
  identifier: string;
  name: string;
  serial: string;
  model: string;
  /** Pool the drive belongs to; null once it left (e.g. after a replacement). */
  pool: string | null;
  /** Counters as last seen; only increases above this count as new errors. */
  baseline: DriveErrorCounts;
  /** Whether the drive was FAULTED/REMOVED/UNAVAIL when last seen. */
  failed: boolean;
  phase: 'ok' | 'checking' | 'watching' | 'attention';
  watchUntil: string | null;
  lastErrorAt: string | null;
  /** Last time ApexOs itself reset this drive's counters (it does so at most once a month). */
  lastClearedAt: string | null;
  diagnosis: DriveDiagnosis | null;
  diagnosisNote: string | null;
  /** The diagnosis of an earlier episode (e.g. "check cable"), so advice that didn't help isn't repeated. */
  previousDiagnosis: DriveDiagnosis | null;
  /** Diagnoses the user has already been told about for the current episode (one notice per episode). */
  notified: DriveDiagnosis[];
  /** The pool check ApexOs runs for the current episode. */
  check: { pool: string; requestedAt: string; startedAt: string | null; attempts: number } | null;
  smart: SmartSummary | null;
  /** Newest first, capped. */
  events: DriveHealthEvent[];
}

export interface DriveHealthStore {
  drives: Record<string, DriveHealthRecord>;
  /** Pool → end time of the last check whose unreadable data was already reported (non-redundant pools). */
  dataLoss: Record<string, string>;
}

/** Two-factor sign-in for the admin account. The TOTP secret never leaves the server after enrollment. */
export interface TwoFactorRecord {
  /** Base32 TOTP secret. */
  secret: string;
  enabledAt: string;
  /** Newest TOTP step accepted so far; codes from this step or earlier are refused (replay protection). */
  lastUsedStep: number;
  /** scrypt hashes of the unused recovery codes; a code's hash is removed when it is used. */
  recoveryCodes: string[];
}

export interface SecurityState {
  /** Bumped by "Sign out everywhere", password changes and turning on 2FA; older session cookies stop working. */
  sessionGeneration: number;
  /** Whether the current password looked strong when it was set; null when unknown. */
  strongPassword: boolean | null;
  twoFactor: TwoFactorRecord | null;
  /** Enrollment started but not yet confirmed with a code. */
  pendingTwoFactor: { secret: string; createdAt: string } | null;
}

/** Remote access ApexOs set up. Auth keys and tunnel tokens are not kept here (only in the TrueNAS app config). */
export interface RemoteAccessState {
  tailscale: {
    appName: string;
    hostname: string;
    /** Subnets advertised to the tailnet ("share my home network"). */
    routes: string[];
    controlServer: string | null;
    /** The IPv4 forwarding sysctl ApexOs created or changed for subnet routing; undone on Turn off. */
    ipForwarding: { tunableId: number; created: boolean; previous: { value: string; enabled: boolean } | null } | null;
    /** Address and name seen when the user opened ApexOs through Tailscale. */
    tailnetIp: string | null;
    tailnetName: string | null;
    enabledAt: string;
  } | null;
  cloudflare: {
    appName: string;
    /** Public hostname the user configured in Cloudflare (informational). */
    publicHostname: string | null;
    enabledAt: string;
  } | null;
}

/** Another TrueNAS server that keeps copies of this server's folders (see services/backups.ts). */
export interface BackupDestinationRecord {
  id: string;
  name: string;
  /** Base URL the user entered, normalized (https://host[:port]). */
  address: string;
  apiUrl: string;
  /** API key for the other server's TrueNAS (ApexOs's own key there when it created one). */
  apiKey: string;
  /** Id of that key when ApexOs created it (deleted again when the destination is removed). */
  apiKeyId: number | null;
  pool: string;
  /** `<pool>/apexos-backups`; `containerCreated` when ApexOs created it. */
  container: string;
  containerCreated: boolean;
  /** `<pool>/apexos-backups/<this server>`: quota and reservation hold the granted space. */
  rootDataset: string;
  /** Restricted receiving account on the other server. */
  username: string;
  sshHost: string;
  sshPort: number;
  sshEnabledByApexOs: boolean;
  /** Keychain entries on this server. */
  keypairId: number;
  credentialId: number;
  grantedBytes: number;
  encryptedOnly: boolean;
  createdAt: string;
  /** Last notified problem state (one notice per change). */
  alert: 'ok' | 'unreachable' | 'nearly-full' | 'full';
  unreachableSince: string | null;
}

/** One folder backed up to one destination: a periodic snapshot task and a PUSH replication task here. */
export interface BackupRecord extends BackupOptions {
  id: string;
  folder: string;
  dataset: string;
  destinationId: string;
  remoteDataset: string;
  namingSchema: string;
  snapshotTaskId: number;
  replicationId: number;
  /** Whether the folder was encrypted when its copy started (a change breaks the copy's history). */
  encrypted: boolean;
  createdAt: string;
  lastSuccessAt: string | null;
  alert: 'ok' | 'failed' | 'overdue' | 'needs-fresh-copy';
}

/** Removal work for a destination that was offline; retried until it is back. */
export interface PendingCleanupRecord {
  id: string;
  kind: 'copy' | 'destination';
  destinationName: string;
  apiUrl: string;
  apiKey: string;
  apiKeyId: number | null;
  /** Dataset to delete (a folder's copy, or the whole per-server dataset). */
  dataset: string;
  username?: string;
  container?: string;
  containerCreated?: boolean;
  sshEnabledByApexOs?: boolean;
  since: string;
  attempts: number;
  lastError: string | null;
}

export interface BackupsState {
  /** Identifies this ApexOs install on the servers it backs up to. */
  serverId: string;
  destinations: BackupDestinationRecord[];
  jobs: BackupRecord[];
  cleanups: PendingCleanupRecord[];
}

export interface ApexOsState {
  version: 1;
  /** Secret used to sign session cookies. */
  sessionSecret: string;
  admin?: {
    username: string;
    passwordHash: string;
  };
  truenas?: {
    url: string;
    apiKey: string;
  };
  server: {
    name?: string;
    setupCompletedAt?: string;
  };
  preferences: StoredPreferences;
  /** ZFS pool name → display name chosen by the user. */
  poolNames: Record<string, string>;
  apps: Record<string, InstalledAppRecord>;
  notices: ApexOsNotice[];
  driveHealth: DriveHealthStore;
  security: SecurityState;
  remoteAccess: RemoteAccessState;
  /** Recovery-file tracking and "turn on encryption" runs (never passphrases). */
  encryption?: StoredEncryption;
  backups: BackupsState;
  /** Pool name → the app data (`<pool>/ix-apps`) TrueNAS left there when ApexOs moved apps away. */
  oldAppData?: Record<string, OldAppDataRecord>;
  /** Folders being moved to another pool, or moved with their old copy still kept. */
  folderMoves?: FolderMoveRecord[];
}

/** Moving a folder (dataset tree) to another pool: copy, switch over, then keep the old copy for a while. */
export interface FolderMoveRecord {
  id: string;
  /** Folder name, e.g. "Media". */
  name: string;
  /** `<old pool>/<name>` and `<new pool>/<name>`. */
  source: string;
  target: string;
  /** Hidden copy on the new pool that becomes the folder at the switch-over. */
  temp: string;
  /** Hidden name the old folder gets at the switch-over (it is kept as the old copy). */
  original: string;
  status: 'running' | 'failed' | 'done';
  step: string | null;
  error: string | null;
  taskId: string | null;
  renamedOriginal: boolean;
  /** The copy took the folder's place; from here on the move is finished, not undone. */
  switched: boolean;
  /** The folder's own SMB share, paused for the switch-over. */
  share: { id: number; wasEnabled: boolean } | null;
  /** Apps ApexOs stopped for the switch-over (started again at the end). */
  stoppedApps: string[];
  warnings: string[];
  startedAt: string;
  removeAfter: string | null;
}

export interface OldAppDataRecord {
  /** Pool the apps moved to. */
  movedTo: string;
  movedAt: string;
  /** When ApexOs removes it on its own. */
  removeAfter: string;
}

function defaultState(): ApexOsState {
  return {
    version: 1,
    sessionSecret: randomBytes(32).toString('base64url'),
    server: {},
    preferences: { locations: {} },
    poolNames: {},
    apps: {},
    notices: [],
    driveHealth: { drives: {}, dataLoss: {} },
    security: { sessionGeneration: 0, strongPassword: null, twoFactor: null, pendingTwoFactor: null },
    remoteAccess: { tailscale: null, cloudflare: null },
    backups: { serverId: randomBytes(8).toString('hex'), destinations: [], jobs: [], cleanups: [] },
  };
}

/** Small JSON-file store. Writes are serialized and atomic (write + rename). */
export class StateStore {
  private state: ApexOsState = defaultState();
  private writing: Promise<void> = Promise.resolve();
  readonly file: string;

  constructor(dataDir: string) {
    this.file = join(dataDir, 'state.json');
  }

  async load(): Promise<void> {
    try {
      const raw = JSON.parse(await readFile(this.file, 'utf8')) as Partial<ApexOsState>;
      const defaults = defaultState();
      this.state = {
        ...defaults,
        ...raw,
        server: { ...raw.server },
        preferences: { locations: {}, ...raw.preferences },
        poolNames: { ...raw.poolNames },
        apps: { ...raw.apps },
        notices: raw.notices ?? [],
        driveHealth: { drives: { ...raw.driveHealth?.drives }, dataLoss: { ...raw.driveHealth?.dataLoss } },
        security: { ...defaults.security, ...raw.security },
        remoteAccess: { ...defaults.remoteAccess, ...raw.remoteAccess },
        backups: { ...defaultState().backups, ...raw.backups },
      };
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
      await this.persist();
    }
  }

  get(): Readonly<ApexOsState> {
    return this.state;
  }

  async update(mutate: (state: ApexOsState) => void): Promise<void> {
    const next = structuredClone(this.state);
    mutate(next);
    this.state = next;
    await this.persist();
  }

  private persist(): Promise<void> {
    const snapshot = JSON.stringify(this.state, null, 2);
    this.writing = this.writing.then(async () => {
      await mkdir(dirname(this.file), { recursive: true, mode: 0o700 });
      const tmp = `${this.file}.tmp`;
      await writeFile(tmp, snapshot, { mode: 0o600 });
      await rename(tmp, this.file);
    });
    return this.writing;
  }
}
